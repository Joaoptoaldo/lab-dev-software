    private void btnAtualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAtualizarActionPerformed
        String sexo = null;
        
        if (rdo_masculino.isSelected()) {
            sexo = "M";
        } else if (rdo_feminino.isSelected()) {
            sexo = "F";
        }
        
        Pessoa p = new Pessoa();
        
        p.setId(Integer.parseInt(txt_ID.getText()));
        p.setNome(txtNome.getText());
        p.setIdioma(cmbIdioma.getSelectedItem().toString());
        
        PessoaDAO pDAO = new PessoaDAO();
        pDAO.editar(p);
        
        limparFormulario();
    }//GEN-LAST:event_btnAtualizarActionPerformed

    private void btnExlcuirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnExlcuirActionPerformed
        int resposta = JOptionPane.showConfirmDialog(null, "Deseja realmente excluir?", "Exclusao", JOptionPane.YES_NO_OPTION);
        
        if(resposta == JOptionPane.YES_OPTION){
            PessoaDAO pDAO = new PessoaDAO();
            pDAO.excluir(Integer.parseInt(txt_ID.getText()));
            
            limparFormulario();
        }
    }//GEN-LAST:event_btnExlcuirActionPerformed

